import sqlite3
from pathlib import Path
import os

# Определяем путь к базе данных относительно этого файла
BASE_DIR = Path(__file__).resolve().parent
DB_PATH = BASE_DIR / "sevara.db"


def get_conn():
    """Создает подключение к БД и устанавливает фабрику строк для удобного доступа по ключам."""
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(DB_PATH))
    # ВАЖНО: Это позволяет обращаться к полям как item['column_name'], а не по индексам
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    """Создает таблицы, если они не существуют."""
    with get_conn() as conn:
        cur = conn.cursor()

        # Таблица инструкций (для будущего расширения)
        cur.execute("""
            CREATE TABLE IF NOT EXISTS instructions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                role TEXT NOT NULL,
                key TEXT NOT NULL,
                text_content TEXT,
                description TEXT,
                photo_file_id TEXT,
                video_file_id TEXT,
                UNIQUE(role, key)
            )
        """)

        # Таблица регламентов (основная для кнопок "Регламенты и штрафы")
        cur.execute("""
            CREATE TABLE IF NOT EXISTS regulations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                category TEXT NOT NULL,
                title TEXT NOT NULL,
                full_text TEXT NOT NULL,
                sort_order INTEGER DEFAULT 0
            )
        """)
        conn.commit()


